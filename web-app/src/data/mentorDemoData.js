/** Cohort summary derived from the centralized demo records. */
export function getCohortStats(students = DEMO_STUDENTS, achievements = DEMO_ACHIEVEMENTS) {
  const totalStudents = students.length;
  const testsTaken = students.reduce((sum, student) => sum + student.testsTaken, 0);
  const activeStudents = students.filter((student) => student.active).length;
  const averageProgress = totalStudents
    ? Math.round(students.reduce((sum, student) => sum + student.progress, 0) / totalStudents)
    : 0;

  return {
    totalStudents,
    testsTaken,
    skillsAchieved: achievements.length,
    activeStudents,
    averageProgress,
  };
}

/** Weighted average demo score across the cohort (weighted by tests taken). */
export function getAverageDemoScore(students = DEMO_STUDENTS) {
  const tests = students.reduce((sum, student) => sum + student.testsTaken, 0);
  if (!tests) return 0;
  const weightedTotal = students.reduce(
    (sum, student) => sum + student.averageScore * student.testsTaken,
    0,
  );
  return Math.round(weightedTotal / tests);
}

export function getProgressTier(progress) {
  if (progress >= 75) return 'Advanced';
  if (progress >= 50) return 'On Track';
  return 'Needs Attention';
}

export function getStudentAchievements(studentId, achievements = DEMO_ACHIEVEMENTS) {
  return achievements.filter((achievement) => achievement.studentId === studentId);
}

